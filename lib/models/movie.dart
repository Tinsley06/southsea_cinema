class Movie {
  final String id;
  final String title;
  final String synopsis;
  final String age_rating;
  final String screening_time;
  final String ticket_price;
  final String poster_image_path;

  Movie({
    required this.id,
    required this.title,
    required this.synopsis,
    required this.age_rating,
    required this.screening_time,
    required this.ticket_price,
    required this.poster_image_path,
  });
}


